// Measures Chromium's break opportunities under word-break: break-all between every ordered pair of the line-breaking
// model's characters (src/text.mjs), and writes them to packages/veriss/src/text-break-all.mjs.
// Each pair is rendered at width 0, where every break opportunity becomes a line break; lang en and ja must agree.
// Characters of a group whose pairs all agree (Latin-1 letters, ideographs and kana, small kana, iteration marks) stand
// for the rest of the group (text.mjs maps them). Usage: node tools/measure-break-all.mjs
import {chromium} from 'playwright';
import {writeFileSync} from 'node:fs';

const ascii = Array.from({length: 94}, (_, i) => String.fromCharCode(33 + i));
const chars = [...ascii, ...'éßÀ·', ...'日本語あかん', ...'ぁっゃ', ...'アカン', ...'ァッャ', 'ー', ...'々ヽゝ', ...'「『（［【〈《〔', ...'」』）］】〉》〕', ...'、。，．・：；！？〜…‥'];
const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const html = lang => `<!doctype html><html lang="${lang}"><head><meta charset="utf-8"><style>body{margin:0;font:16px/20px sans-serif}div{width:0;word-break:break-all;margin-bottom:60px}</style></head><body>${chars.flatMap(x => chars.map(y => `<div>${escape(x + y)}</div>`)).join('')}</body></html>`;

const browser = await chromium.launch(), page = await browser.newPage(), measured = {};
for (const lang of ['en', 'ja']) {
  await page.setContent(html(lang));
  measured[lang] = await page.evaluate(() => [...document.querySelectorAll('div')].map(d => {
    const t = d.firstChild, r = document.createRange(), cs = [...t.data];
    const top = i => { const off = cs.slice(0, i).join('').length; r.setStart(t, off); r.setEnd(t, off + cs[i].length); return r.getBoundingClientRect().top; };
    return top(1) > top(0) + 1 ? '1' : '0';
  }).join(''));
}
await browser.close();
if (measured.en !== measured.ja) throw new Error('lang en and ja disagree; the table would depend on the language');
// Groups must agree with every character, on both sides.
const n = chars.length, at = new Map(chars.map((c, i) => [c, i])), bit = (x, y) => measured.en[at.get(x) * n + at.get(y)];
for (const group of ['éßÀ', '日本語あかんアカン', 'ぁっゃァッャ', '々ヽゝ']) for (const x of chars) for (const g of group) {
  if (bit(x, g) !== bit(x, group[0]) || bit(g, x) !== bit(group[0], x)) throw new Error(`${group} is not uniform next to ${x}`);
}
// Packed: one bit a pair, row-major, as base64.
const bytes = new Uint8Array(Math.ceil(n * n / 8));
[...measured.en].forEach((b, i) => { if (b === '1') bytes[i >> 3] |= 1 << (i & 7); });
writeFileSync(new URL('../packages/veriss/src/text-break-all.mjs', import.meta.url), `// Generated by tools/measure-break-all.mjs from Chromium ${browser.version?.() ?? ''}: break opportunities under
// word-break: break-all between every ordered pair of these characters (a break before the second), measured at width 0
// with lang en and ja (they agree). Do not edit; run the tool again.
export const breakAllCharacters = ${JSON.stringify(chars.join(''))};
export const breakAllPairs = ${JSON.stringify(Buffer.from(bytes).toString('base64'))};
`);
console.log(`${n} characters, ${[...measured.en].filter(b => b === '1').length} breaks`);
